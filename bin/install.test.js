#!/usr/bin/env node
// Regression tests for the npm launcher installer.
//
// The release workflow generates SHA256SUMS with `sha256sum release/db-mcp-server-*`,
// so every entry carries a `release/` path prefix while the asset the installer
// downloads is the bare file name. `findChecksum` used to compare the whole
// field, so every install failed with "no SHA-256 checksum found for ..."
// (caught by installing the packed tarball).
//
// Run with: node --test bin/install.test.js

const assert = require("node:assert/strict");
const test = require("node:test");

const { findChecksum } = require("./install.js");

// Shape of the real v1.13.0 release asset, generated by the workflow.
const RELEASE_SUMS = [
  "302c610d8299d6c7161fb8c01d3e00bb2855efd1c2a8a4ce61c16880db84fef5  release/db-mcp-server-darwin-amd64",
  "2ba669ff628649bef9bbb8e9704c3e9ee72202ba078c1219300758df52edc45a  release/db-mcp-server-darwin-arm64",
  "71310222bb17f715d5edd7edb0fe4be71a3f8573028c0cd2b0087dc894a1fd9d  release/db-mcp-server-linux-amd64",
  "a991c8cf40a64c83c2f97f138c5a40b1277e9e512ffb7efd0313bdddee2a223c  release/db-mcp-server-windows-amd64.exe",
].join("\n");

test("matches an asset listed with a release/ path prefix", () => {
  assert.equal(
    findChecksum(Buffer.from(RELEASE_SUMS), "db-mcp-server-darwin-arm64"),
    "2ba669ff628649bef9bbb8e9704c3e9ee72202ba078c1219300758df52edc45a",
  );
});

test("matches a windows asset with the .exe suffix and path prefix", () => {
  assert.equal(
    findChecksum(Buffer.from(RELEASE_SUMS), "db-mcp-server-windows-amd64.exe"),
    "a991c8cf40a64c83c2f97f138c5a40b1277e9e512ffb7efd0313bdddee2a223c",
  );
});

test("still matches a bare file name (no prefix)", () => {
  const sums = "abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789  db-mcp-server-linux-arm64\n";
  assert.equal(
    findChecksum(Buffer.from(sums), "db-mcp-server-linux-arm64"),
    "abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789",
  );
});

test("accepts the binary-mode star marker", () => {
  const sums = "abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789 *release/db-mcp-server-linux-amd64\n";
  assert.equal(
    findChecksum(Buffer.from(sums), "db-mcp-server-linux-amd64"),
    "abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789",
  );
});

test("lowercases the digest so comparison is case-insensitive", () => {
  const sums = "ABCDEF0123456789ABCDEF0123456789ABCDEF0123456789ABCDEF0123456789  release/db-mcp-server-darwin-amd64\n";
  assert.equal(
    findChecksum(Buffer.from(sums), "db-mcp-server-darwin-amd64"),
    "abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789",
  );
});

test("throws for an asset that is genuinely absent", () => {
  assert.throws(
    () => findChecksum(Buffer.from(RELEASE_SUMS), "db-mcp-server-freebsd-amd64"),
    /no SHA-256 checksum found for db-mcp-server-freebsd-amd64/,
  );
});

test("ignores blank lines and header noise", () => {
  const sums = ["", "  ", "# comment", "abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789  release/db-mcp-server-linux-arm64"].join("\n");
  assert.equal(
    findChecksum(Buffer.from(sums), "db-mcp-server-linux-arm64"),
    "abcdef0123456789abcdef0123456789abcdef0123456789abcdef0123456789",
  );
});

test("does not match a different architecture of the same platform", () => {
  assert.throws(
    () => findChecksum(Buffer.from(RELEASE_SUMS), "db-mcp-server-linux-arm64"),
    /no SHA-256 checksum found/,
  );
});
